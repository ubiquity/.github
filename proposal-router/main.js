import { createIssueUrl, inferTitle, rankRepositories, repositoryKey, resolveRepositorySelection } from "./router.js";

export const CATALOG_UNAVAILABLE_NOTICE = "Repository catalog unavailable. Serve this folder over HTTP and reload.";

export async function initProposalRouter({ doc = globalThis.document, fetchFn = globalThis.fetch, nav = globalThis.navigator } = {}) {
  const proposalInput = doc.querySelector("#proposal");
  const titleInput = doc.querySelector("#title");
  const repositorySelect = doc.querySelector("#repository");
  const suggestionsList = doc.querySelector("#suggestions");
  const issueLink = doc.querySelector("#issue-link");
  const copyButton = doc.querySelector("#copy-link");

  let repositories = [];
  let currentSuggestions = [];
  let renderedOptionKeys = null;
  // Set only by a user action (choosing in the select or clicking a suggestion).
  // While set, proposal edits never retarget the issue link on their own.
  let explicitSelectionKey = null;
  let titleWasAutoGenerated = true;

  async function loadRepositories() {
    try {
      const response = await fetchFn("./repositories.json");
      if (!response.ok) {
        throw new Error(`Repository catalog request failed with HTTP ${response.status}`);
      }
      const catalog = await response.json();
      if (!Array.isArray(catalog) || catalog.length === 0) {
        throw new Error("Repository catalog is empty");
      }
      repositorySelect.disabled = false;
      return catalog;
    } catch {
      const notice = doc.createElement("li");
      notice.textContent = CATALOG_UNAVAILABLE_NOTICE;
      suggestionsList.replaceChildren(notice);
      repositorySelect.disabled = true;
      return [];
    }
  }

  function renderRepositoryOptions(options, selectedKey) {
    const signature = options.join("\n");
    if (signature !== renderedOptionKeys) {
      repositorySelect.replaceChildren(
        ...options.map((key) => {
          const option = doc.createElement("option");
          option.value = key;
          option.textContent = key;
          return option;
        })
      );
      renderedOptionKeys = signature;
    }

    if (selectedKey) {
      repositorySelect.value = selectedKey;
    }
  }

  function renderSuggestions() {
    suggestionsList.replaceChildren(
      ...currentSuggestions.map(({ repository, matchScore, matched }) => {
        const key = repositoryKey(repository);
        const item = doc.createElement("li");
        const header = doc.createElement("div");
        const title = doc.createElement("strong");
        const score = doc.createElement("span");
        const description = doc.createElement("p");
        const matches = doc.createElement("small");

        header.className = "suggestion-header";
        title.textContent = key;
        score.textContent = `Keyword match score: ${matchScore}`;
        description.textContent = repository.description;
        matches.textContent = matched.length ? `Matched: ${matched.join(", ")}` : "Waiting for proposal detail";

        header.append(title, score);
        item.append(header, description, matches);
        item.addEventListener("click", () => {
          explicitSelectionKey = key;
          repositorySelect.value = key;
          updateIssueLink();
        });
        return item;
      })
    );
  }

  function selectedRepository() {
    return repositories.find((repository) => repositoryKey(repository) === repositorySelect.value) ?? null;
  }

  function updateIssueLink() {
    const title = titleInput.value.trim();
    const body = proposalInput.value.trim();
    const repository = selectedRepository();
    const enabled = Boolean(title && body && repository);

    issueLink.href = enabled ? createIssueUrl(repository, title, body) : "#";
    issueLink.setAttribute("aria-disabled", String(!enabled));
  }

  function updateSuggestions() {
    const proposal = proposalInput.value;

    if (titleWasAutoGenerated) {
      titleInput.value = inferTitle(proposal);
    }

    if (repositories.length === 0) {
      updateIssueLink();
      return;
    }

    currentSuggestions = rankRepositories(repositories, proposal, 5);

    const { options, selected } = resolveRepositorySelection(repositories, currentSuggestions, explicitSelectionKey);
    renderRepositoryOptions(options, selected);
    renderSuggestions();

    updateIssueLink();
  }

  let copyFeedbackTimer;

  function showCopyFeedback(label, hint) {
    copyButton.textContent = label;
    copyButton.title = hint ?? "";
    clearTimeout(copyFeedbackTimer);
    copyFeedbackTimer = setTimeout(() => {
      copyButton.textContent = "Copy Link";
      copyButton.title = "";
    }, 1400);
  }

  repositories = await loadRepositories();

  proposalInput.addEventListener("input", updateSuggestions);
  titleInput.addEventListener("input", () => {
    titleWasAutoGenerated = false;
    updateIssueLink();
  });
  repositorySelect.addEventListener("change", () => {
    explicitSelectionKey = repositorySelect.value;
    updateIssueLink();
  });
  copyButton.addEventListener("click", async () => {
    if (issueLink.getAttribute("aria-disabled") === "true") {
      return;
    }
    try {
      if (!nav?.clipboard?.writeText) {
        throw new Error("Clipboard API unavailable");
      }
      await nav.clipboard.writeText(issueLink.href);
      showCopyFeedback("Copied");
    } catch {
      showCopyFeedback("Copy failed", "Clipboard blocked. Copy the address from the Open GitHub Issue link instead.");
    }
  });

  if (repositories.length > 0) {
    updateSuggestions();
  }
}

if (typeof document !== "undefined") {
  await initProposalRouter();
}
