import { createIssueUrl, inferTitle, rankRepositories } from "./router.js";

const repositories = await fetch("./repositories.json").then((response) => response.json());

const proposalInput = document.querySelector("#proposal");
const titleInput = document.querySelector("#title");
const repositorySelect = document.querySelector("#repository");
const suggestionsList = document.querySelector("#suggestions");
const issueLink = document.querySelector("#issue-link");
const copyButton = document.querySelector("#copy-link");

let currentSuggestions = [];
let titleWasAutoGenerated = true;

function renderRepositoryOptions() {
  repositorySelect.replaceChildren(
    ...currentSuggestions.map(({ repository }) => {
      const option = document.createElement("option");
      option.value = `${repository.owner}/${repository.name}`;
      option.textContent = `${repository.owner}/${repository.name}`;
      return option;
    })
  );
}

function renderSuggestions() {
  suggestionsList.replaceChildren(
    ...currentSuggestions.map(({ repository, confidence, matched }) => {
      const item = document.createElement("li");
      const header = document.createElement("div");
      const title = document.createElement("strong");
      const score = document.createElement("span");
      const description = document.createElement("p");
      const matches = document.createElement("small");

      header.className = "suggestion-header";
      title.textContent = `${repository.owner}/${repository.name}`;
      score.textContent = `${confidence}%`;
      description.textContent = repository.description;
      matches.textContent = matched.length ? `Matched: ${matched.join(", ")}` : "Waiting for proposal detail";

      header.append(title, score);
      item.append(header, description, matches);
      item.addEventListener("click", () => {
        repositorySelect.value = `${repository.owner}/${repository.name}`;
        updateIssueLink();
      });
      return item;
    })
  );
}

function selectedRepository() {
  return repositories.find((repository) => `${repository.owner}/${repository.name}` === repositorySelect.value) ?? repositories[0];
}

function updateIssueLink() {
  const title = titleInput.value.trim();
  const body = proposalInput.value.trim();
  const enabled = Boolean(title && body);

  issueLink.href = enabled ? createIssueUrl(selectedRepository(), title, body) : "#";
  issueLink.setAttribute("aria-disabled", String(!enabled));
}

function updateSuggestions() {
  const proposal = proposalInput.value;
  currentSuggestions = rankRepositories(repositories, proposal, 5);
  renderRepositoryOptions();
  renderSuggestions();

  if (titleWasAutoGenerated) {
    titleInput.value = inferTitle(proposal);
  }

  updateIssueLink();
}

proposalInput.addEventListener("input", updateSuggestions);
titleInput.addEventListener("input", () => {
  titleWasAutoGenerated = false;
  updateIssueLink();
});
repositorySelect.addEventListener("change", updateIssueLink);
copyButton.addEventListener("click", async () => {
  if (issueLink.getAttribute("aria-disabled") === "true") {
    return;
  }
  await navigator.clipboard.writeText(issueLink.href);
  copyButton.textContent = "Copied";
  setTimeout(() => {
    copyButton.textContent = "Copy Link";
  }, 1400);
});

updateSuggestions();
